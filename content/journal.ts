/** Hebrew dateline, e.g. "7 בספטמבר 2026". */
export function journalDate(iso: string): string {
  return new Date(iso).toLocaleDateString("he-IL", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}
