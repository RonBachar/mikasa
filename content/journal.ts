/**
 * Everything released. The index, the sitemap, llms.txt and the cluster
 * blocks all read this rather than `journalPosts`, so a draft is invisible
 * everywhere except its own URL.
 */
export const publishedPosts = journalPosts.filter((p) => !p.draft);

/** Post lookup by slug, drafts included — the route serves them for review. */
export const journalBySlug: Record<string, JournalPost> = Object.fromEntries(
  journalPosts.map((p) => [p.slug, p])
);

/** Released posts in a cluster, minus the one asking. Order: pillar first. */
export function clusterSiblings(post: JournalPost): JournalPost[] {
  return publishedPosts
    .filter((p) => p.cluster === post.cluster && p.slug !== post.slug)
    .sort((a, b) => Number(b.pillar ?? false) - Number(a.pillar ?? false));
}

/** Released clusters, in the release order declared by `clusters`. */
export function publishedClusters(): { id: ClusterId; posts: JournalPost[] }[] {
  return (Object.keys(clusters) as ClusterId[])
    .map((id) => ({ id, posts: publishedPosts.filter((p) => p.cluster === id) }))
    .filter((c) => c.posts.length > 0);
}

