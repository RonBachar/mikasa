/**
 * "היומן של מיקאסה" — the guesthouse journal.
 *
 * Why this section exists, in SEO terms: the site ranks at position 1 for
 * "מיקאסה שעל" and page 2 for everything a person searches when they do NOT
 * already know the name. The commercial head terms are worse than page 2 —
 * a live SERP check on 2026-09-10 found all ten results for "צימרים ברמת
 * הגולן" held by aggregator directories (Weekend, Zimmer, RRR, Booking and
 * friends), with no independent guesthouse anywhere on the page. A two-suite
 * property does not outrank those. What the directories do not write is what
 * is at Saar waterfall, when the cherries ripen, or how a snow day at Hermon
 * actually goes — searches with real volume and near-zero competition. Each
 * post below takes one of those and links back to /area and the suites.
 *
 * Posts are grouped into clusters (see `clusters`). One post per cluster is
 * the pillar: it targets the cluster's biggest term and links to the other
 * four, which link back. That shape is the whole point — five posts that
 * reference each other rank better than five that stand alone.
 *
 * The honesty rule from content/pricing.ts applies here too and matters more,
 * because these posts talk about places we do not run: nothing states an
 * opening hour, an entry fee, a trail length or a snow condition as fact.
 * Everything time-sensitive is written as "check before you go", because a
 * guest who drove 40 minutes to a closed gate blames the site that sent them.
 * Owner (Mika) reviews every factual claim before a post leaves `draft`.
 */

