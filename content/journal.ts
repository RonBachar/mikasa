export type JournalPost = {
  slug: string;
  /**
   * This post's share card. Named explicitly rather than built from the slug
   * so the OgCard union still guarantees the file exists — a template string
   * would need a cast, and a cast is exactly how a 404 share image ships.
   */
  ogCard: OgCard;
  /** Which cluster this belongs to. Drives the "more in this cluster" block. */
  cluster: ClusterId;
  /**
   * The cluster's anchor post — the one targeting its biggest search term.
   * Exactly one per cluster; `pillarFor` below enforces nothing at runtime,
   * so keep it to one by hand.
   */
  pillar?: boolean;
  /**
   * Written but not released. A draft is reachable at its own URL so Mika can
   * read it, and is otherwise invisible: no sitemap entry, no llms.txt line,
   * not on the index, and `noindex` in its own head. Flip it to released by
   * deleting this line — that is the whole weekly-release ritual.
   */
  draft?: boolean;
  /** The h1. Written as the question a person types, not as a headline. */
  title: string;
  metaTitle: string;
  metaDescription: string;
  /** Card copy on the index, and the hero body on the post itself. */
  excerpt: string;
  /** ISO date. Also the dateline the post shows. */
  date: string;
  /**
   * ISO date of the last real revision, for `dateModified`. Omitted until the
   * post is actually revised: a dateModified that moves on every deploy tells
   * Google the content changed when it did not.
   */
  updated?: string;
  readMinutes: number;
  /** Manifest file — owner photography only, same rule as everywhere else. */
  heroImage: string;
  /** Short label on the card, e.g. "מסלול מוצע". */
  tag: string;
  /**
   * Citational opening: two or three sentences that answer the title outright,
   * before any atmosphere. This is the paragraph an answer engine quotes, and
   * the one a skimmer reads instead of the whole post.
   */
  lead: string;
  sections: JournalSection[];
  /**
   * Required, not optional. These become the post's FAQPage markup and they
   * are the part of the page an answer engine lifts verbatim — a post without
   * them is a post that ranks and never gets quoted. Write the questions as
   * people type them, including the ones Google itself shows under "People
   * also ask" for the target term.
   */
  faqs: Faq[];
  /** Closing line in Mika's voice. Optional. */
  closing?: string;
};

