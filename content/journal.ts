/**
 * "היומן של מיקאסה" — the guesthouse journal.
 *
 * Why this section exists, in SEO terms: the site ranks at position 1 for
 * "מיקאסה שעל" and page 2 for everything a person searches when they do NOT
 * already know the name — "צימרים שעל", "מושב שעל צימרים", "אכסניה ברמת
 * הגולן". Nine pages of booking copy cannot rank for those; pages that
 * actually answer the question can. Each post below targets one such question
 * and links back to /area and the suites.
 *
 * The honesty rule from content/pricing.ts applies here too and matters more,
 * because these posts talk about places we do not run: nothing states an
 * opening hour, an entry fee, a trail length or a snow condition as fact.
 * Everything time-sensitive is written as "check before you go", because a
 * guest who drove 40 minutes to a closed gate blames the site that sent them.
 * Owner (Mika) to review every factual claim before this goes out.
 */

import type { OgCard } from "@/lib/seo";

export type JournalSection = {
  heading: string;
  paragraphs: string[];
  /** Optional bullet list, rendered after the paragraphs. */
  list?: string[];
};

export type JournalPost = {
  slug: string;
  /**
   * This post's share card. Named explicitly rather than built from the slug
   * so the OgCard union still guarantees the file exists — a template string
   * would need a cast, and a cast is exactly how a 404 share image ships.
   */
  ogCard: OgCard;
  /** The h1. Written as the question a person types, not as a headline. */
  title: string;
  metaTitle: string;
  metaDescription: string;
  /** Card copy on the index, and the hero body on the post itself. */
  excerpt: string;
  /** ISO date. Also the dateline the post shows. */
  date: string;
  readMinutes: number;
  /** Manifest file — owner photography only, same rule as everywhere else. */
  heroImage: string;
  /** Short label on the card, e.g. "מסלול מוצע". */
  tag: string;
  /**
   * Citational opening: two or three sentences that answer the title outright,
   * before any atmosphere. This is the paragraph an answer engine quotes, and
   * the one a skimmer reads instead of the whole post.
   */
  lead: string;
  sections: JournalSection[];
  /** Closing line in Mika's voice. Optional. */
  closing?: string;
};

